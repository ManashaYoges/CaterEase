/**
 * Get translated text for given key and language.
 * Falls back to English / key if missing.
 */
export function translate(key: string, lang: Language = 'en', params?: Record<string, string | number>): string {
  const entry = translations[key];
  let text = entry ? (entry[lang] || entry['en'] || key) : key;

  if (params) {
    Object.keys(params).forEach(pKey => {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(params[pKey]));
    });
  }

  return text;
}
